-- 依据：《数据库与数据层设计说明书》§9.2（初始化数据）、§4.7（队列序号表脚本）、
--       §9.8.1（密码必须为不可逆哈希）、DEC-06、DEC-32、DEC-DB-12
-- 配套：任务清单任务 6
--
-- 内容两项：
--   ① 队列序号行 (id = 1, current_value = 0)              —— §4.7
--   ② 卖家账号 1 条 (account = 'seller')                   —— §9.2
--
-- 幂等性（§9.2「必须幂等」）：
--   两项都用 INSERT ... ON DUPLICATE KEY UPDATE 实现：重复执行不产生第 2 行。
--   账号行另有 uk_user_account 唯一索引兜底；序号行由主键 id = 1 兜底。
--
-- ⚠️ 密码口径（DEC-DB-12 第 ③ 条：不得把明文写入任何 SQL 脚本或版本库）：
--   本脚本**只写入 BCrypt 哈希**，不出现任何明文口令。
--   BCrypt 为不可逆哈希（C-17、DEC-06），编码固定 60 字符，与列宽 varchar(100) 相容。
--
-- ⚠️ 已知取舍（须让评审看到）：初始口令是**约定的固定值**（否则交付后无法登录），
--   因此「哈希入库」虽满足「不存明文」，却不能提供保密性——凡能读到本仓库者，
--   即知道该初始口令。缓解措施：① 交付文档给出**改密步骤**（R12-05）；
--   ② 首次登录后必须改密（改密流程属应用层）。详见 README「初始账号与改密」。
-- =============================================================================


-- -----------------------------------------------------------------------------
-- ① 队列序号行　　　　　　　　　　　　　　　　　　　　§4.7 · DEC-DB-03
--    单行表：id 固定为 1；current_value 保存「已分配的最大 queue_order」，初值 0。
--    该行必须在应用启动前存在，否则序号的 findAll/加锁取数拿不到行。
-- -----------------------------------------------------------------------------
INSERT INTO `simpleshop_queue_sequence` (`id`, `current_value`)
VALUES (1, 0)
ON DUPLICATE KEY UPDATE `id` = `id`;


-- -----------------------------------------------------------------------------
-- ② 卖家账号（单账号，FR-01）　　　　　　　　　　　　§9.2 · DEC-06、DEC-32
--    account  = 'seller'
--    password = BCrypt 哈希（强度 10）
--    id       = 固定 UUID（前缀 U，§10.7；此处为常量，非随机生成）
--
--    时间列用 UTC_TIMESTAMP()：与 C-10「库内即为 UTC」一致，
--    不用 NOW()（后者取会话时区，本机为 UTC+8，会写入本地时间）。
-- -----------------------------------------------------------------------------
INSERT INTO `simpleshop_users` (`id`, `account`, `password`, `create_at`, `update_at`)
VALUES (
  'U0000000-0000-4000-8000-000000000001',
  'seller',
  '$2a$10$OHzqM5qU3fCLG/ixnx/EReXS6NHnT37EpZyavH3Zkff2T4YjVZ3R6',
  UTC_TIMESTAMP(),
  UTC_TIMESTAMP()
)
ON DUPLICATE KEY UPDATE `id` = `id`;
