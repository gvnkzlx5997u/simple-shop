package com.simpleshop.service.dto;

/**
 * 买家端的「提示码」：把「判定条件」与「界面文案」绑在一处（第 11 章 §11.6.2）。
 *
 * <h2>⚠️ 这不是传输契约，与卖家端的 {@code ErrorCode} 是两套东西</h2>
 * <p>§11.6.2 的标题原文就写着「<b>买家端业务结果对照（服务端内部约定，非契约）</b>」：
 * <blockquote>
 * 买家端为服务端渲染，<b>不用 HTTP 业务码</b>；服务端在渲染时<b>直接选择</b>提示文案。
 * </blockquote>
 * <p>因此本枚举<b>不是</b>给前端解析的码，而是服务端自己「选哪句文案」的依据。两点推论：
 * <ol>
 *   <li><b>不得并入 {@code ErrorCode}</b>：那是卖家端 REST 的错误码表，
 *       §4.3 明确「<b>不得增删编号</b>」，把买家文案塞进去会污染那份契约表，
 *       也会让「{@code 1xxxx}~{@code 5xxxx} 各归其域」的归属规则失效。</li>
 *   <li><b>文案直接放在这里（中文）</b>，而<b>不是</b>像卖家端那样只给 ASCII 英文的调试信息。
 *       这<b>不</b>违反已定 Q-13（{@code message} 用英文）：Q-13 管的是<b>卖家 REST 响应里的
 *       {@code message} 字段</b>——那是给日志看的、前端不许展示；而买家端是<b>服务端渲染</b>，
 *       文案本来就由服务端产生并直接印到 HTML 上。两处的“谁负责渲染”不同，故语言不同。</li>
 * </ol>
 *
 * <h2>⚠️ 文案属于「需求文本」，不属于「需要被测试钉住的代码常量」</h2>
 * <p>本枚举<b>只保留文案本身</b>，不再携带 {@code M10-xx}／{@code B11-xx}／是否【必须】等结构化元数据，
 * 也<b>没有</b>任何逐字比对文案的测试。理由：
 * <ul>
 *   <li>文案的唯一权威是第 10 章 §10.5《提示文案表》。把它的原文<b>再抄一份</b>进测试，
 *       等于制造第二个权威——改文案要同时改两处，而测试里的那一份<b>不会</b>因此变得更可靠；</li>
 *   <li>「哪几条是【必须】」是<b>验收口径</b>（{@code AC-28}），由评审对着 §10.5 走查即可判定；
 *       把它编码成枚举字段 + 断言，收益是「构建立刻失败」，代价是需求改一个字就误报一次红灯。</li>
 * </ul>
 * <p>文案的溯源信息（{@code M10-xx} 编号、上游 {@code B11-xx} 编号、是否【必须】）
 * 以注释形式逐条写在下方常量上——<b>给人看</b>，不给构建看。
 *
 * <h2>⚠️ 字段命名与「B11-xx」的双重含义</h2>
 * <p>第 11 章里 {@code B11-01}~{@code B11-07} <b>同时</b>是买家端<b>页面端点编号</b>
 * （§11.x 端点表：{@code B11-01} = 当前商品页 {@code GET /}）与<b>结果编号</b>
 * （§11.6.2 结果表：{@code B11-01} = 冻结期提交被拒）。编号撞车是<b>上游文档的既有问题</b>，
 * 故本枚举<b>不</b>用 {@code B11-xx} 当常量名，而用<b>含义命名</b>（{@code GOODS_FROZEN}）。
 * 这样代码里不会出现「{@code B11_01} 到底是页面还是结果」的歧义。
 *
 * <h2>⚠️ 两个「无上游编号」的成员</h2>
 * <p>{@link #GOODS_UNAVAILABLE}（{@code M10-13}）与 {@link #TOO_MANY_REQUESTS} 在 §11.6.2 里
 * <b>没有</b>对应的 {@code B11-xx}：前者是「提交时商品已非在售（并发）」，方案 §3.3.5 把它与
 * 冻结混写在一行（原稿「空 或 goods.status != on_sale → B11-01 / M10-13」），
 * 但 {@code B11-01} 的条件明确是「<b>商品处于交易冻结</b>」，与「商品没了/已下架」不是一回事，
 * 文案也不同（{@code M10-01} vs {@code M10-13}）。本实现<b>按条件拆成两条</b>，
 * 并<b>不擅自给 {@code M10-13} 编一个 {@code B11-11}</b>——编号只由上游分配。
 */
public enum BuyerPrompt {

    // -------------------------------------------------------------------------
    // P10-01 当前商品页
    // -------------------------------------------------------------------------

    /**
     * 商品处于冻结（<b>手动</b>或<b>交易</b>两种来源都算），提交意向被拒。
     *
     * <p>文案 {@code M10-01}（{@code 【必须】}，{@code AC-28}），上游结果 {@code B11-01}。
     * {@code AC-17}（{@code P0}）明确要求两种冻结来源<b>一律拒绝</b>并展示本句——故这里
     * <b>不</b>按冻结来源分文案。（本句措辞是「商品交易中…」，用在手动冻结上略不贴切，
     * 但 {@code AC-17} 是逐字规定的，实现不自行改文案；已在 §8.10 登记为口径观察项。）
     */
    GOODS_FROZEN("商品交易中，暂停接收新意向"),

    /** 无当前商品（表内无行）：空态，不显示商品卡片。文案 {@code M10-02}；上游未分配结果编号。 */
    NO_CURRENT_GOODS("暂无在售商品"),

    /** 提交时商品已非在售（并发导致的状态变化，含商品行已不存在）。文案 {@code M10-13}；上游未分配结果编号。 */
    GOODS_UNAVAILABLE("商品状态已变化，无法提交"),

    // -------------------------------------------------------------------------
    // P10-02 提交表单页
    // -------------------------------------------------------------------------

    /** 姓名或电话为空。文案 {@code M10-11}；上游结果 {@code B11-03}。 */
    NAME_TEL_REQUIRED("请填写姓名与联系电话"),

    /** 姓名超长或含非法字符。文案 {@code M10-36}；上游结果 {@code B11-03}。 */
    NAME_INVALID("姓名不超过 50 个字符，且不能包含 < >，首尾不要留空格"),

    /** 电话格式不符。文案 {@code M10-37}；上游结果 {@code B11-03}。 */
    TEL_INVALID("请填写正确的联系电话（7~20 位数字，可含 -）"),

    /** 队列已达 1000 条上限。文案 {@code M10-12}；上游结果 {@code B11-02}。 */
    QUEUE_FULL("当前排队人数已达上限，暂时无法提交"),

    /** 提交过于频繁（{@code NFR-17} 的基础限流）。出处：第 12 章 {@code P6}，第 10 章无对应 {@code M10-xx}。 */
    TOO_MANY_REQUESTS("请稍后重试"),

    // -------------------------------------------------------------------------
    // P10-03 提交成功页
    // -------------------------------------------------------------------------

    /**
     * 展示口令码并提醒保存。
     *
     * <p>文案 {@code M10-04}（{@code 【必须】}，{@code AC-28}）。
     *
     * <p>⚠️ <b>本项不由 Service 返回</b>：成功页由 JSP 直接渲染，但文案属 {@code AC-28} 的
     * 5 条【必须】之一，故一并收在此处，让「必须文案」有<b>唯一来源</b>。
     *
     * <p>⚠️ 上游<b>没有</b>对应编号：§11.6.2 的 {@code B11-xx} 是<b>业务结果</b>对照表，
     * 其中没有「提交成功」这一行（{@code B11-10} 是「修改信息成功」，{@code B11-03} 是
     * 「姓名／电话校验失败」）。{@code B11-03} 在端点表里（§11.x）才表示「提交意向」这个
     * <b>页面端点</b>——那正是编号撞车的另一面，故此处<b>不</b>借用它当结果编号。
     */
    SAVE_PASSCODE("请立即保存您的口令码：XXXXXXXXXXXX。此码仅显示这一次，丢失后无法自助找回"),

    // -------------------------------------------------------------------------
    // P10-04 口令码查询页
    // -------------------------------------------------------------------------

    /** 口令码不存在（错误口令）。文案 {@code M10-05}；上游结果 {@code B11-04}。 */
    PASSCODE_NOT_FOUND("口令不正确，请检查后重试"),

    /**
     * 口令码已失效（意向处于终态）。
     *
     * <p>文案 {@code M10-06}（{@code 【必须】}，{@code AC-28}）；上游结果 {@code B11-05}。
     *
     * <p>⚠️ <b>不得说明原因、不得透露交易结果、不得返回买家信息</b>
     * （{@code BR-29}、{@code NFR-13}、{@code M10-06} 的原文要求）。
     * 本实现在<b>类型层</b>落实这条：{@link PasscodeQueryResult.Expired} 是<b>零字段</b>记录，
     * 想「顺手带出状态」都表达不出来（见该类的说明）。
     */
    PASSCODE_EXPIRED("该口令码已失效"),

    /**
     * 口令码有效 · 意向排队中。
     *
     * <p>文案 {@code M10-07}（{@code 【必须】}，{@code AC-28}）；上游结果 {@code B11-06}。
     * 文案里的 {@code N} 由渲染方用位次替换。
     */
    QUEUED_RANK("您当前排第 N 位"),

    /** 口令码有效 · 意向交易中（{@code trading} 不占位次，故不显示位次）。文案 {@code M10-08}（{@code 【必须】}）；上游结果 {@code B11-07}。 */
    ENTERED_TRADE("您已进入交易"),

    /** 意向处于交易中，撤销被拒。文案 {@code M10-14}；上游结果 {@code B11-08}。 */
    REVOKE_NOT_ALLOWED("您的意向已进入交易，无法撤销"),

    /** 口令码长度／格式不符（非 12 位）。文案 {@code M10-28}；上游结果 {@code B11-09}。 */
    PASSCODE_MALFORMED("请输入 12 位口令码（大写字母与数字）");

    private final String text;

    BuyerPrompt(String text) {
        this.text = text;
    }

    /**
     * 界面文案原文（第 10 章 §10.5《提示文案表》逐字，{@code M10-07} 的 {@code N} 为占位符）。
     *
     * <p>本方法是本枚举<b>唯一</b>的对外读取口——刻意不再提供编号/等级等元数据访问器：
     * 那些信息只服务于「人核对需求」，以注释形式写在常量上即可（见类注释）。
     */
    public String text() {
        return text;
    }
}
